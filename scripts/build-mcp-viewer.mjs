#!/usr/bin/env node
/* Builds the MCP App view ui://monge/model-viewer.html: mcp-app/viewer.js with the site's own Three.js (r177,
   public/vendor/three, MIT) bundled into one inline script inside mcp-app/viewer.html — a self-contained page that
   loads nothing but the models' GLB and WebP. Writes lib/mcp-viewer-html.generated.ts (committed). */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const THREE = path.join(root, 'public/vendor/three/build/three.module.min.js');
const JSM = path.join(root, 'public/vendor/three/examples/jsm');

const res = await build({
  entryPoints: [path.join(root, 'mcp-app/viewer.js')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2020'],
  write: false,
  legalComments: 'inline',
  plugins: [{
    name: 'vendored-three',
    setup(b) {
      b.onResolve({ filter: /^three(\/addons\/.*)?$/ }, (a) => ({ path: a.path === 'three' ? THREE : path.join(JSM, a.path.slice('three/addons/'.length)) }));
    },
  }],
});
const js = res.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = readFileSync(path.join(root, 'mcp-app/viewer.html'), 'utf8').replace('<!--APP_JS-->', () => `<script>${js}</script>`);
const sha = createHash('sha256').update(html).digest('hex');
writeFileSync(
  path.join(root, 'lib/mcp-viewer-html.generated.ts'),
  `/* GENERATED by scripts/build-mcp-viewer.mjs from mcp-app/ — do not edit. Three.js r177 © three.js authors, MIT. */\n` +
    `export const VIEWER_SHA = '${sha}';\nexport const VIEWER_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`mcp viewer: ${(html.length / 1024).toFixed(0)} KB, sha256 ${sha.slice(0, 12)}`);
